#!/usr/bin/env python3
"""Corpus WER and bounded end-to-end evaluation; no network or microphone access.

References are never generated by the recognizer under test. Manifest WAVs must
be PCM16 mono 16 kHz. Output contains transcripts: keep restricted corpora local.
"""
import argparse
import json
import os
from pathlib import Path
import platform
import re
import unicodedata
import wave
from dictation import run, digest


def words(text):
    # Keep umlauts and ß distinct. Do not silently translate dialects or expand
    # numbers. Apostrophes/punctuation split words; NFC avoids combining-form bias.
    return re.findall(r'[^\W_]+', unicodedata.normalize('NFC', text).lower())


def score(reference, hypothesis):
    r, h = words(reference), words(hypothesis)
    # Rows of (total errors, substitutions, deletions, insertions). Deterministic
    # tie-break: diagonal, deletion, insertion; WER is invariant to this choice.
    prev = [(j, 0, 0, j) for j in range(len(h)+1)]
    for i, token in enumerate(r, 1):
        cur = [(i, 0, i, 0)]
        for j, other in enumerate(h, 1):
            e,s,d,ins=prev[j-1]; mismatch=int(token != other)
            diagonal=(e+mismatch,s+mismatch,d,ins)
            e,s,d,ins=prev[j]; deletion=(e+1,s,d+1,ins)
            e,s,d,ins=cur[j-1]; insertion=(e+1,s,d,ins+1)
            cur.append(min((diagonal,deletion,insertion),key=lambda v:v[0]))
        prev=cur
    e,s,d,i=prev[-1]
    return dict(errors=e,substitutions=s,deletions=d,insertions=i,
                reference_words=len(r),wer=e/len(r) if r else None)


def aggregate(results):
    groups={}
    for result in results:
        group=groups.setdefault(result['group'],dict(clips=0,errors=0,reference_words=0,
                    substitutions=0,deletions=0,insertions=0,audio_s=0,wall_s=0,failed=0))
        group['clips']+=1
        group['failed']+=int(bool(result.get('timeout') or result['exit_code']))
        for key in ('errors','reference_words','substitutions','deletions','insertions','audio_s','wall_s'):
            group[key]+=result[key]
    for g in groups.values():
        g['wer']=g['errors']/g['reference_words'] if g['reference_words'] else None
        g['wall_rtf']=g['wall_s']/g['audio_s'] if g['audio_s'] else None
    return groups


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--manifest',type=Path,required=True)
    ap.add_argument('--engine',choices=['geist','whisper'],default='geist')
    ap.add_argument('--model-sha256')
    for name in ('binary','model','tower','mel','output'):
        ap.add_argument('--'+name,type=Path,required=name not in ('tower','mel'))
    ap.add_argument('--threads',type=int,default=4)
    ap.add_argument('--timeout',type=float,default=1800)
    ap.add_argument('--paced',action='store_true')
    ap.add_argument('--groups',default='')
    ap.add_argument('--limit',type=int,default=0)
    args=ap.parse_args(); args.reference=None
    for name in ('binary','model','tower','mel'):
        if getattr(args,name) is not None:setattr(args,name,getattr(args,name).resolve(strict=True))
    hashes={name:digest(getattr(args,name)) for name in ('binary','model','tower','mel') if getattr(args,name) is not None}
    expected = dict(model='740185b21d22ceb83a11c3aa62ad5842ef32c70f6096d756bbee85a1e4ec34b8',
                    tower='d6c45a6c276212dc3a793e66dfc588d89c12d1ac92c0e4b85494390ca848cd77')
    if args.engine=='whisper':
        if not args.model_sha256:ap.error('--model-sha256 required for alternative engine')
        expected={'model':args.model_sha256}
    if args.engine=='geist' and (args.tower is None or args.mel is None):ap.error('Geist requires --tower and --mel')
    if any(hashes.get(k) != v for k,v in expected.items()):
        ap.error('model/tower SHA-256 differs from the audit baseline')
    fixtures=json.loads(args.manifest.read_text())
    groups=args.groups.split(',') if args.groups else None
    fixtures=[f for f in fixtures if not groups or f['group'] in groups]
    if args.limit:fixtures=fixtures[:args.limit]
    if not fixtures:ap.error('no matching fixtures')
    report=dict(engine=args.engine,platform=platform.platform(),threads=args.threads,paced=args.paced,
        environment={k:v for k,v in os.environ.items() if k.startswith('GEIST_AUDIO_') or k=='OMP_WAIT_POLICY'},
        files=hashes,manifest_sha256=digest(args.manifest),
        normalization='NFC lowercase; Unicode letters/digits; punctuation split; no number/dialect rewriting',
        cache_policy='fresh process per fixture; hashes read before runs; warm OS caches',runs=[])
    if args.engine=='whisper':
        import shutil
        cli=shutil.which(os.environ.get('GEIST_WHISPER_CLI','whisper-cli'))
        if not cli:ap.error('GEIST_WHISPER_CLI / whisper-cli missing')
        report['whisper_cli_sha256']=digest(cli)
        report['resource_scope']='wait4 child usage; descendant maximum RSS is not summed; adapter reloads CPU model per segment'
    args.output.parent.mkdir(parents=True,exist_ok=True)
    for fixture in fixtures:
        path=args.manifest.parent/fixture['wav']
        if digest(path)!=fixture['sha256']:raise ValueError('fixture hash mismatch: '+str(path))
        with wave.open(str(path)) as wav:
            if (wav.getframerate(),wav.getnchannels(),wav.getsampwidth())!=(16000,1,2):raise ValueError('invalid WAV format')
            pcm=wav.readframes(wav.getnframes())
        result=run(args,pcm+bytes(32000),len(pcm)/32000)
        hypothesis=' '.join(result['transcript'])
        result.update(id=fixture['id'],group=fixture['group'],wav_sha256=fixture['sha256'])
        result.update(score(fixture['reference'],hypothesis))
        if fixture.get('dialect_reference'):
            result['dialect_score']=score(fixture['dialect_reference'],hypothesis)
        if args.paced and result.get('output_times_s'):
            result['last_output_after_audio_end_s']=result['output_times_s'][-1]-result['feed_start_s']-result['audio_s']
            result['feed_backlog_s']=max(0,result.get('feed_finished_s',0)-result['feed_start_s']-(len(pcm)+32000)/32000)
        report['runs'].append(result);report['groups']=aggregate(report['runs'])
        args.output.write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
        print(json.dumps({k:result.get(k) for k in ('id','wer','wall_s','peak_rss_mib','exit_code','timeout')},ensure_ascii=False),flush=True)
    return int(any(r['exit_code'] or r.get('timeout') for r in report['runs']))


if __name__=='__main__':raise SystemExit(main())
